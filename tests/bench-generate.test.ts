import { parse } from 'yaml';
import { describe, expect, it } from 'vitest';
import { generateBenchFiles, unresolvedTokens } from '../src/bench/generate';
import { emptyProfile } from '../src/bench/profile';
import type { BenchProfile, HardwareCatalog } from '../src/bench/types';

export const fixtureCatalog: HardwareCatalog = {
  usbDevices: [],
  boards: [],
  pduModels: [
    { model: 'netio', family: 'NETIO 4', indexBase: 1, indexMax: 4, hostFormat: 'host', confidence: 'source' },
    { model: 'shelly_gen2', family: 'Shelly Gen2', indexBase: 0, hostFormat: 'url', confidence: 'source' },
    { model: 'eaton', family: 'Eaton ePDU', indexBase: 1, indexMax: 16, hostFormat: 'host', requirements: ['pip install "labgrid[snmp]"'], confidence: 'source' },
  ],
};

function localProfile(): BenchProfile {
  return {
    ...emptyProfile(),
    board: { name: 'Raspberry Pi 4' },
    devices: [
      { id: 'dev-1', kind: 'usb-serial', label: 'Console', match: { ID_PATH: 'pci-0000:00:14.0-usb-0:1.3:1.0' }, speed: 115200, usbId: { vendorId: '10c4', productId: 'ea60' } },
      { id: 'dev-2', kind: 'network-pdu', label: 'PDU', model: 'netio', host: 'pdu.lab', index: 3 },
    ],
    login: { username: 'root', prompt: 'root@[\\w-]+:[^ ]+ ', loginPrompt: ' login: ' },
    bootloader: { kind: 'uboot', prompt: 'U-Boot> ' },
  };
}

function remoteProfile(): BenchProfile {
  return {
    ...emptyProfile(),
    board: { name: 'ZCU102' },
    topology: 'remote',
    sharing: 'team',
    names: { place: 'zcu102-01', group: 'rack-3-zcu102', exporterHost: 'labhost', coordinator: '127.0.0.1:20408', location: 'Rack 3' },
    devices: [
      { id: 'dev-1', kind: 'usb-serial', label: 'Console A', match: { ID_SERIAL_SHORT: 'FT1ABC', ID_USB_INTERFACE_NUM: '00' }, speed: 115200 },
      { id: 'dev-2', kind: 'usb-serial', label: 'Console B', match: { ID_SERIAL_SHORT: 'FT1ABC', ID_USB_INTERFACE_NUM: '01' }, speed: 115200 },
      { id: 'dev-3', kind: 'ykush', label: 'Power', serial: 'Y3N12345', index: '1' },
    ],
  };
}

function byName(files: ReturnType<typeof generateBenchFiles>, filename: string) {
  const file = files.find((candidate) => candidate.filename === filename);
  if (!file) throw new Error(`missing ${filename}: ${files.map((f) => f.filename).join(', ')}`);
  return file;
}

describe('generateBenchFiles', () => {
  it('renders a complete local environment in Labgrid order', () => {
    const files = generateBenchFiles(localProfile(), fixtureCatalog);
    expect(files.map((file) => file.filename)).toEqual(['environment.yaml', 'SETUP.md', 'bench-profile.json']);
    const env = byName(files, 'environment.yaml');
    expect(env.kind).toBe('environment');
    expect(env.unresolved).toEqual([]);
    const parsed = parse(env.content) as { targets: { main: { resources: Record<string, unknown>; drivers: Record<string, unknown> } } };
    expect(Object.keys(parsed.targets.main.resources)).toEqual(['USBSerialPort', 'NetworkPowerPort']);
    expect(parsed.targets.main.resources.USBSerialPort).toEqual({ match: { ID_PATH: 'pci-0000:00:14.0-usb-0:1.3:1.0' }, speed: 115200 });
    expect(parsed.targets.main.resources.NetworkPowerPort).toEqual({ model: 'netio', host: 'pdu.lab', index: 3 });
    expect(Object.keys(parsed.targets.main.drivers)).toEqual([
      'SerialDriver',
      'NetworkPowerDriver',
      'ShellDriver',
      'UBootDriver',
      'UBootStrategy',
    ]);
    expect(parsed.targets.main.drivers.ShellDriver).toEqual({ prompt: 'root@[\\w-]+:[^ ]+ ', login_prompt: ' login: ', username: 'root' });
    expect(parsed.targets.main.drivers.UBootDriver).toEqual({ prompt: 'U-Boot> ' });
    expect(env.content.startsWith('# Generated by Labgrid Setup Advisor')).toBe(true);
    expect(env.content).toContain('# Board: Raspberry Pi 4');
    expect(env.content).not.toContain('Generated at');
  });

  it('uses cls entries and named bindings when a resource class repeats', () => {
    const files = generateBenchFiles(remoteProfile(), fixtureCatalog);
    expect(files.map((file) => file.filename)).toEqual(['exporter.yaml', 'remote.yaml', 'SETUP.md', 'bench-profile.json']);

    const exporter = parse(byName(files, 'exporter.yaml').content) as Record<string, Record<string, unknown>>;
    const group = exporter['rack-3-zcu102'];
    expect(group.location).toBe('Rack 3');
    expect(group['console-a']).toEqual({ cls: 'USBSerialPort', match: { ID_SERIAL_SHORT: 'FT1ABC', ID_USB_INTERFACE_NUM: '00' }, speed: 115200 });
    expect(group['console-b']).toEqual({ cls: 'USBSerialPort', match: { ID_SERIAL_SHORT: 'FT1ABC', ID_USB_INTERFACE_NUM: '01' }, speed: 115200 });
    expect(group.YKUSHPowerPort).toEqual({ serial: 'Y3N12345', index: '1' });
    expect(byName(files, 'exporter.yaml').content).toMatch(/index: '1'/);

    const remote = parse(byName(files, 'remote.yaml').content) as { targets: { main: { resources: unknown; drivers: Array<Record<string, Record<string, unknown>>> } } };
    expect(remote.targets.main.resources).toEqual({ RemotePlace: { name: 'zcu102-01' } });
    expect(Array.isArray(remote.targets.main.drivers)).toBe(true);
    expect(remote.targets.main.drivers[0]).toEqual({ SerialDriver: { name: 'console-a-driver', bindings: { port: 'console-a' } } });
    expect(remote.targets.main.drivers[1]).toEqual({ SerialDriver: { name: 'console-b-driver', bindings: { port: 'console-b' } } });
    expect(remote.targets.main.drivers[2]).toEqual({ YKUSHPowerDriver: {} });
    expect(byName(files, 'remote.yaml').content).not.toContain('&a');
  });

  it('binds shell and strategy drivers to the first console when several exist', () => {
    const profile = remoteProfile();
    profile.login = { username: 'root', prompt: 'root@[\\w-]+:[^ ]+ ', loginPrompt: ' login: ' };
    const remote = parse(byName(generateBenchFiles(profile, fixtureCatalog), 'remote.yaml').content) as {
      targets: { main: { drivers: Array<Record<string, Record<string, unknown>>> } };
    };
    const shell = remote.targets.main.drivers.find((driver) => 'ShellDriver' in driver)?.ShellDriver;
    expect(shell?.bindings).toEqual({ console: 'console-a-driver' });
    const strategy = remote.targets.main.drivers.find((driver) => 'ShellStrategy' in driver)?.ShellStrategy;
    expect(strategy).toEqual({ name: 'strategy', bindings: { console: 'console-a-driver' } });
  });

  it('names every power control when two different controllers exist', () => {
    const profile = localProfile();
    profile.devices = [
      { id: 'dev-1', kind: 'usb-serial', label: 'Console', match: { ID_SERIAL_SHORT: 'A50285BI' }, speed: 115200 },
      { id: 'dev-2', kind: 'network-pdu', label: 'Outlet', model: 'netio', host: 'pdu.lab', index: 1 },
      { id: 'dev-3', kind: 'ykush', label: 'USB power', serial: 'Y3N1', index: '2' },
    ];
    delete profile.bootloader;
    const env = parse(byName(generateBenchFiles(profile, fixtureCatalog), 'environment.yaml').content) as {
      targets: { main: { resources: Array<Record<string, Record<string, unknown>>>; drivers: Array<Record<string, Record<string, unknown>>> } };
    };
    expect(env.targets.main.resources).toEqual([
      { USBSerialPort: { match: { ID_SERIAL_SHORT: 'A50285BI' }, speed: 115200 } },
      { NetworkPowerPort: { name: 'outlet', model: 'netio', host: 'pdu.lab', index: 1 } },
      { YKUSHPowerPort: { name: 'usb-power', serial: 'Y3N1', index: '2' } },
    ]);
    expect(env.targets.main.drivers).toEqual([
      { SerialDriver: {} },
      { NetworkPowerDriver: { name: 'outlet-driver', bindings: { port: 'outlet' } } },
      { YKUSHPowerDriver: { name: 'usb-power-driver', bindings: { port: 'usb-power' } } },
      { ShellDriver: { name: 'shell', prompt: 'root@[\\w-]+:[^ ]+ ', login_prompt: ' login: ', username: 'root' } },
      { ShellStrategy: { name: 'strategy', bindings: { power: 'outlet-driver' } } },
    ]);
  });

  it('writes placeholders for missing values and reports them', () => {
    const profile = localProfile();
    profile.devices = [
      { id: 'dev-1', kind: 'usb-serial', label: 'Console', match: {}, speed: 115200 },
      { id: 'dev-2', kind: 'network-pdu', label: 'PDU', model: 'netio', host: '', index: 1 },
      { id: 'dev-3', kind: 'ykush', label: 'YKUSH', serial: '', index: '' },
    ];
    delete profile.login;
    delete profile.bootloader;
    const env = byName(generateBenchFiles(profile, fixtureCatalog), 'environment.yaml');
    expect(env.unresolved).toEqual(['ID_SERIAL_SHORT', 'PDU_HOST', 'YKUSH_SERIAL', 'YKUSH_PORT_INDEX']);
    // Two power controls force the list form; collect the entries by class.
    const parsed = parse(env.content) as { targets: { main: { resources: Array<Record<string, Record<string, unknown>>> } } };
    const byClass = Object.assign({}, ...parsed.targets.main.resources) as Record<string, Record<string, unknown>>;
    expect(byClass.USBSerialPort.match).toEqual({ ID_SERIAL_SHORT: '<ID_SERIAL_SHORT>' });
    expect(byClass.NetworkPowerPort.host).toBe('<PDU_HOST>');
    expect(byClass.YKUSHPowerPort).toEqual({ name: 'ykush', serial: '<YKUSH_SERIAL>', index: '<YKUSH_PORT_INDEX>' });
  });

  it('keeps empty match values as placeholders while preserving the chosen key', () => {
    const profile = localProfile();
    profile.devices = [{ id: 'dev-1', kind: 'usb-serial', label: 'Console', match: { '@ID_PATH': '' }, speed: 115200 }];
    delete profile.login;
    delete profile.bootloader;
    const env = byName(generateBenchFiles(profile, fixtureCatalog), 'environment.yaml');
    expect(env.content).toContain("'@ID_PATH': <ID_PATH>");
    expect(env.unresolved).toEqual(['ID_PATH']);
    expect(() => parse(env.content)).not.toThrow();
  });

  it('emits a systemd drop-in only for a non-default coordinator', () => {
    const profile = remoteProfile();
    expect(generateBenchFiles(profile, fixtureCatalog).some((file) => file.kind === 'service')).toBe(false);
    profile.names.coordinator = 'coordinator.lab:20408';
    const files = generateBenchFiles(profile, fixtureCatalog);
    const override = byName(files, 'labgrid-exporter.override.conf');
    expect(override.kind).toBe('service');
    expect(override.target).toBe('exporter-host');
    expect(override.content).toContain('[Service]');
    expect(override.content).toContain('Environment="LG_COORDINATOR=coordinator.lab:20408"');
    expect(override.content).toContain('systemctl edit labgrid-exporter.service');
  });

  it('writes setup notes with the place name and the match command', () => {
    const notes = byName(generateBenchFiles(remoteProfile(), fixtureCatalog), 'SETUP.md');
    expect(notes.kind).toBe('notes');
    expect(notes.content).toContain('| Place | zcu102-01 |');
    expect(notes.content).toContain('labgrid-client -p zcu102-01 add-match labhost/rack-3-zcu102/*');
    expect(notes.content).not.toContain('add-named-match');
    expect(notes.content).toContain('come from the keys in exporter.yaml');
    expect(notes.content).toContain('`exporter.yaml` (exporter-host)');
    expect(notes.content).toContain('- Console A: USB serial console (115200 baud)');
  });

  it('uses ManualPowerDriver without a power resource', () => {
    const profile = localProfile();
    profile.devices = [
      { id: 'dev-1', kind: 'usb-serial', label: 'Console', match: { ID_SERIAL_SHORT: 'A50285BI' }, speed: 115200 },
      { id: 'dev-2', kind: 'manual-power', label: 'Hand switch' },
    ];
    delete profile.bootloader;
    const env = parse(byName(generateBenchFiles(profile, fixtureCatalog), 'environment.yaml').content) as {
      targets: { main: { resources: Record<string, unknown>; drivers: Record<string, unknown> } };
    };
    expect(Object.keys(env.targets.main.resources)).toEqual(['USBSerialPort']);
    expect(env.targets.main.drivers.ManualPowerDriver).toEqual({ name: 'Raspberry Pi 4' });
    expect(Object.keys(env.targets.main.drivers)).toEqual(['SerialDriver', 'ManualPowerDriver', 'ShellDriver', 'ShellStrategy']);
  });

  it('passes URL hosts through unchanged for URL based backends', () => {
    const profile = localProfile();
    profile.devices = [{ id: 'dev-1', kind: 'network-pdu', label: 'Shelly', model: 'shelly_gen2', host: 'http://192.168.0.42', index: 0 }];
    delete profile.login;
    delete profile.bootloader;
    const env = parse(byName(generateBenchFiles(profile, fixtureCatalog), 'environment.yaml').content) as {
      targets: { main: { resources: Record<string, Record<string, unknown>>; drivers: Record<string, unknown> } };
    };
    expect(env.targets.main.resources.NetworkPowerPort).toEqual({ model: 'shelly_gen2', host: 'http://192.168.0.42', index: 0 });
    expect(env.targets.main.drivers).toEqual({ NetworkPowerDriver: {} });
  });

  it('includes the profile as JSON and keeps output deterministic', () => {
    const first = generateBenchFiles(localProfile(), fixtureCatalog);
    const second = generateBenchFiles(localProfile(), fixtureCatalog);
    expect(first).toEqual(second);
    const profile = byName(first, 'bench-profile.json');
    expect(profile.kind).toBe('profile');
    expect(JSON.parse(profile.content)).toEqual(localProfile());
    const stamped = generateBenchFiles(localProfile(), fixtureCatalog, { generatedAt: new Date('2026-10-31T10:00:00Z') });
    expect(byName(stamped, 'environment.yaml').content).toContain('# Generated at: 2026-10-31T10:00:00.000Z');
  });

  it('falls back to board-01 names and renders debugger, dfu, fastboot and storage resources', () => {
    const profile = emptyProfile();
    profile.topology = 'remote';
    profile.names = { place: '', group: '', exporterHost: '', coordinator: '', location: '' };
    profile.devices = [
      { id: 'dev-1', kind: 'usb-debugger', label: 'Probe', match: { ID_PATH: 'pci-0000:00:14.0-usb-0:2:1.0' }, interfaceConfig: 'interface/stlink.cfg', boardConfig: 'board/st_nucleo_f4.cfg' },
      { id: 'dev-2', kind: 'dfu', label: 'DFU', match: { ID_PATH: 'pci-0000:00:14.0-usb-0:3:1.0' } },
      { id: 'dev-3', kind: 'fastboot', label: 'Fastboot', match: { ID_PATH: 'pci-0000:00:14.0-usb-0:4:1.0' }, usbId: { vendorId: '18d1', productId: '4ee0' } },
      { id: 'dev-4', kind: 'usb-sd-mux', label: 'SD mux', match: { '@ID_PATH': 'pci-0000:00:14.0-usb-0:1.2' } },
      { id: 'dev-5', kind: 'network-service', label: 'SSH', address: '192.168.1.20', username: 'root', port: 22 },
    ];
    const files = generateBenchFiles(profile, fixtureCatalog);
    const exporter = parse(byName(files, 'exporter.yaml').content) as Record<string, Record<string, unknown>>;
    expect(Object.keys(exporter)).toEqual(['board-01']);
    expect(exporter['board-01'].AndroidUSBFastboot).toEqual({ match: { ID_PATH: 'pci-0000:00:14.0-usb-0:4:1.0' }, usb_vendor_id: '18d1', usb_product_id: '4ee0' });
    expect(exporter['board-01'].USBSDMuxDevice).toEqual({ match: { '@ID_PATH': 'pci-0000:00:14.0-usb-0:1.2' } });
    expect(exporter['board-01'].NetworkService).toEqual({ address: '192.168.1.20', username: 'root', port: 22 });
    const remote = parse(byName(files, 'remote.yaml').content) as { targets: { main: { drivers: Record<string, unknown> } } };
    expect(remote.targets.main.drivers).toEqual({
      OpenOCDDriver: { interface_config: 'interface/stlink.cfg', board_config: 'board/st_nucleo_f4.cfg' },
      DFUDriver: {},
      AndroidFastbootDriver: {},
      USBSDMuxDriver: {},
      SSHDriver: {},
    });
    expect(byName(files, 'SETUP.md').content).toContain('<EXPORTER_HOST>');
  });
});

describe('unresolvedTokens', () => {
  it('lists unique angle-bracket tokens', () => {
    expect(unresolvedTokens("a: <ID_PATH>\nb: '<ID_PATH>'\nc: <PDU_HOST>\nd: <lower>")).toEqual(['ID_PATH', 'PDU_HOST']);
  });
});

describe('exporter comment safety', () => {
  it('only writes double-hash comments into exporter files because labgrid-exporter runs Jinja2 with # as the statement prefix', async () => {
    const { generateBenchFiles } = await import('../src/bench/generate');
    const { sampleBenches } = await import('../src/bench/samples');
    const { hardwareCatalog } = await import('../src/bench/catalog');
    for (const sample of sampleBenches) {
      for (const file of generateBenchFiles(sample.profile, hardwareCatalog)) {
        if (file.kind !== 'exporter') continue;
        for (const line of file.content.split('\n')) {
          if (line.trimStart().startsWith('#')) expect(line.trimStart().startsWith('##')).toBe(true);
        }
      }
    }
  });
});

describe('review fixes', () => {
  type Env = { targets: { main: { resources: unknown; drivers: Array<Record<string, Record<string, unknown>>> | Record<string, Record<string, unknown>> } } };

  it('binds the strategy to a named power driver when two PDU outlets exist', () => {
    const profile = localProfile();
    profile.devices = [
      { id: 'dev-1', kind: 'usb-serial', label: 'Console', match: { ID_SERIAL_SHORT: 'A50285BI' }, speed: 115200 },
      { id: 'dev-2', kind: 'network-pdu', label: 'Board outlet', model: 'netio', host: 'pdu.lab', index: 1 },
      { id: 'dev-3', kind: 'network-pdu', label: 'Peripheral outlet', model: 'netio', host: 'pdu.lab', index: 2 },
    ];
    const env = parse(byName(generateBenchFiles(profile, fixtureCatalog), 'environment.yaml').content) as Env;
    const drivers = env.targets.main.drivers as Array<Record<string, Record<string, unknown>>>;
    expect(Array.isArray(drivers)).toBe(true);
    const names = drivers.map((entry) => Object.values(entry)[0].name).filter((name): name is string => typeof name === 'string');
    expect(new Set(names).size).toBe(names.length);
    const strategy = drivers.find((entry) => 'UBootStrategy' in entry)?.UBootStrategy;
    expect(strategy?.bindings).toEqual({ power: 'board-outlet-driver' });
    expect(names).toContain('board-outlet-driver');
    // Every binding value refers to a driver instance name that exists in the list.
    for (const entry of drivers) {
      const bindings = (Object.values(entry)[0].bindings ?? {}) as Record<string, string>;
      for (const [attribute, target] of Object.entries(bindings)) {
        if (attribute === 'power' || attribute === 'console') expect(names).toContain(target);
      }
    }
    const shell = drivers.find((entry) => 'ShellDriver' in entry)?.ShellDriver;
    expect(shell?.bindings).toBeUndefined();
    // The single console needs no name; only ambiguous suppliers and their consumers are named.
    expect(drivers.find((entry) => 'SerialDriver' in entry)?.SerialDriver.name).toBeUndefined();
  });

  it('drops ManualPowerDriver when a real power controller exists', () => {
    const profile = localProfile();
    profile.devices.push({ id: 'dev-3', kind: 'manual-power', label: 'Hand switch' });
    const env = parse(byName(generateBenchFiles(profile, fixtureCatalog), 'environment.yaml').content) as Env;
    expect(Object.keys(env.targets.main.drivers)).toEqual(['SerialDriver', 'NetworkPowerDriver', 'ShellDriver', 'UBootDriver', 'UBootStrategy']);
  });

  it('skips login, bootloader and strategy drivers when no console exists', () => {
    const profile = localProfile();
    profile.devices = [{ id: 'dev-2', kind: 'network-pdu', label: 'PDU', model: 'netio', host: 'pdu.lab', index: 3 }];
    const env = parse(byName(generateBenchFiles(profile, fixtureCatalog), 'environment.yaml').content) as Env;
    expect(Object.keys(env.targets.main.drivers)).toEqual(['NetworkPowerDriver']);
  });

  it('emits AlteraUSBBlaster for a USB-Blaster debugger and lower-cases fastboot ids', () => {
    const profile = localProfile();
    profile.devices = [
      { id: 'dev-1', kind: 'usb-debugger', label: 'USB-Blaster', match: { ID_PATH: 'pci-0000:00:14.0-usb-0:4' }, resourceClass: 'AlteraUSBBlaster', interfaceConfig: 'interface/altera-usb-blaster.cfg' },
      { id: 'dev-2', kind: 'fastboot', label: 'Fastboot', match: { ID_PATH: 'pci-0000:00:14.0-usb-0:5' }, usbId: { vendorId: '18D1', productId: '4EE0' } },
    ];
    delete profile.login;
    delete profile.bootloader;
    const env = parse(byName(generateBenchFiles(profile, fixtureCatalog), 'environment.yaml').content) as {
      targets: { main: { resources: Record<string, Record<string, unknown>>; drivers: Record<string, unknown> } };
    };
    expect(Object.keys(env.targets.main.resources)).toEqual(['AlteraUSBBlaster', 'AndroidUSBFastboot']);
    expect(env.targets.main.resources.AndroidUSBFastboot.usb_vendor_id).toBe('18d1');
    expect(env.targets.main.resources.AndroidUSBFastboot.usb_product_id).toBe('4ee0');
    expect(Object.keys(env.targets.main.drivers)).toEqual(['OpenOCDDriver', 'AndroidFastbootDriver']);
  });

  it('uses a direct ID_PATH placeholder for an empty USB-SD-Mux match', () => {
    const profile = localProfile();
    profile.devices = [{ id: 'dev-1', kind: 'usb-sd-mux', label: 'SD mux', match: {} }];
    delete profile.login;
    delete profile.bootloader;
    const env = byName(generateBenchFiles(profile, fixtureCatalog), 'environment.yaml');
    const parsed = parse(env.content) as { targets: { main: { resources: { USBSDMuxDevice: { match: Record<string, string> } } } } };
    expect(parsed.targets.main.resources.USBSDMuxDevice.match).toEqual({ ID_PATH: '<ID_PATH>' });
    expect(env.unresolved).toEqual(['ID_PATH']);
  });
});
